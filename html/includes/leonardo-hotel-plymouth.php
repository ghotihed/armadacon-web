<p>
    The hotel is located in the heart of Plymouth, a 10-minute walk from the Plymouth train station, and mere
    steps away from top city attractions, including the Historic Quarter and the harbour.
</p>

<div class="content-box">
<h3>Rooms</h3>
<p>
    The Leonardo has a number of different rooms available, with assorted combinations of beds and bed sizes. These
    can accommodate from one to three adults or up to two adults and two children. Accessible rooms are also
    available.
</p>
</div>

<div class="content-box">
<h3>Room Rates</h3>
<p>
    Room rates do not include breakfast; there is an additional charge when pre-booked.
</p>
<p>
    The Leonardo Hotel has a <a href="https://www.leonardohotels.co.uk/leonardo-advantage-club">loyalty membership programme</a>.
    People who sign up for it will receive reduced room rates as well as reduced rates on food and drinks in the
    restaurant and bar.
</p>
</div>

<div class="content-box">
